package com.github.ibanetchep.artisanguilds.storage;

import net.artisanmc.modules.api.database.DatabaseDialect;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.Locale;

/**
 * Creates and upgrades ArtisanGuilds' tables in the database Artisan lends. Forward only, with
 * statements H2, MySQL and MariaDB run the same. The data of MSGuilds is brought in afterwards by
 * {@link LegacyImport}, never in place: MSGuilds' own tables are never touched.
 *
 * <p>Plain JDBC, run once from {@code onEnable}, blocking.
 */
public final class GuildSchema {

    public record Result(int fromVersion, int toVersion) {
        public boolean created() { return fromVersion == 0; }
        public boolean upgraded() { return fromVersion > 0 && toVersion > fromVersion; }
    }

    private final DataSource dataSource;
    private final DatabaseDialect dialect;
    private final GuildTables t;

    public GuildSchema(DataSource dataSource, DatabaseDialect dialect, GuildTables tables) {
        this.dataSource = dataSource;
        this.dialect = dialect;
        this.t = tables;
    }

    /** Append, never edit a released step. */
    private List<List<String>> migrations() {
        String autoId = dialect == DatabaseDialect.H2
                ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                : "BIGINT AUTO_INCREMENT PRIMARY KEY";
        String timestamp = dialect == DatabaseDialect.H2 ? "TIMESTAMP" : "DATETIME";
        return List.of(
                List.of(
                        "CREATE TABLE " + t.guilds() + " ("
                                + "id CHAR(36) NOT NULL PRIMARY KEY, "
                                + "name VARCHAR(255) NOT NULL UNIQUE, "
                                + "balance DOUBLE DEFAULT 0 NOT NULL, "
                                + "exp BIGINT DEFAULT 0 NOT NULL, "
                                + "level INT DEFAULT 1 NOT NULL, "
                                + "home VARCHAR(255) NULL, "
                                + "owner_uuid CHAR(36) NULL, "
                                + "created_at " + timestamp + " DEFAULT CURRENT_TIMESTAMP NOT NULL)",
                        "CREATE TABLE " + t.ranks() + " ("
                                + "id CHAR(36) NOT NULL PRIMARY KEY, "
                                + "guild_id CHAR(36) NOT NULL, "
                                + "label VARCHAR(255) NOT NULL, "
                                + "rank_order INT DEFAULT 0 NOT NULL, "
                                + "permissions TEXT NULL, "
                                + "CONSTRAINT " + t.rankLabelKey() + " UNIQUE (guild_id, label), "
                                + "FOREIGN KEY (guild_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE)",
                        "CREATE TABLE " + t.members() + " ("
                                + "player_uuid CHAR(36) NOT NULL PRIMARY KEY, "
                                + "guild_id CHAR(36) NOT NULL, "
                                + "rank_id CHAR(36) NULL, "
                                + "chat_mode VARCHAR(50) NULL, "
                                + "FOREIGN KEY (guild_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE, "
                                + "FOREIGN KEY (rank_id) REFERENCES " + t.ranks() + "(id))",
                        "CREATE TABLE " + t.logs() + " ("
                                + "id " + autoId + ", "
                                + "guild_id CHAR(36) NOT NULL, "
                                + "log TEXT NULL, "
                                + "created_at " + timestamp + " DEFAULT CURRENT_TIMESTAMP NOT NULL, "
                                + "FOREIGN KEY (guild_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE)",
                        "CREATE TABLE " + t.alliances() + " ("
                                + "guild_a_id CHAR(36) NOT NULL, "
                                + "guild_b_id CHAR(36) NOT NULL, "
                                + "PRIMARY KEY (guild_a_id, guild_b_id), "
                                + "FOREIGN KEY (guild_a_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE, "
                                + "FOREIGN KEY (guild_b_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE)",
                        // One row per import of MSGuilds' data (LegacyImport): it never runs twice.
                        "CREATE TABLE " + t.imports() + " ("
                                + "source VARCHAR(255) NOT NULL, "
                                + "imported_at " + timestamp + " NOT NULL, "
                                + "counts VARCHAR(255) NOT NULL)"),
                // The guild chest: one row per non-empty page, its items as Paper serializes them.
                List.of("CREATE TABLE " + t.chests() + " ("
                        + "guild_id CHAR(36) NOT NULL, "
                        + "page INT NOT NULL, "
                        + "contents " + (dialect == DatabaseDialect.H2 ? "BLOB" : "MEDIUMBLOB") + " NOT NULL, "
                        + "PRIMARY KEY (guild_id, page), "
                        + "FOREIGN KEY (guild_id) REFERENCES " + t.guilds() + "(id) ON DELETE CASCADE)"));
    }

    public Result migrate() throws SQLException {
        try (Connection c = dataSource.getConnection()) {
            execute(c, List.of("CREATE TABLE IF NOT EXISTS " + t.schemaVersion() + " (version INT NOT NULL)"));
            int from = currentVersion(c);
            List<List<String>> steps = migrations();
            for (int i = from; i < steps.size(); i++) {
                execute(c, steps.get(i));
                try (PreparedStatement p = c.prepareStatement("INSERT INTO " + t.schemaVersion() + " (version) VALUES (?)")) {
                    p.setInt(1, i + 1);
                    p.executeUpdate();
                }
            }
            return new Result(from, Math.max(from, steps.size()));
        }
    }

    private int currentVersion(Connection c) throws SQLException {
        try (Statement s = c.createStatement();
             ResultSet r = s.executeQuery("SELECT MAX(version) FROM " + t.schemaVersion())) {
            return r.next() ? r.getInt(1) : 0;
        }
    }

    private static void execute(Connection c, List<String> statements) throws SQLException {
        for (String sql : statements) {
            try (Statement s = c.createStatement()) {
                s.execute(sql);
            }
        }
    }

    /**
     * Looked up in the connection's own database only: MySQL's metadata otherwise searches every
     * database of the server. The name is tried as written, then upper case (H2), then lower case.
     */
    static boolean tableExists(Connection c, String table) throws SQLException {
        DatabaseMetaData meta = c.getMetaData();
        for (String name : spellings(table)) {
            try (ResultSet r = meta.getTables(c.getCatalog(), null, name, new String[]{"TABLE"})) {
                if (r.next()) return true;
            }
        }
        return false;
    }

    static boolean columnExists(Connection c, String table, String column) throws SQLException {
        DatabaseMetaData meta = c.getMetaData();
        for (String tableName : spellings(table)) {
            try (ResultSet r = meta.getColumns(c.getCatalog(), null, tableName, null)) {
                while (r.next()) {
                    if (r.getString("COLUMN_NAME").equalsIgnoreCase(column)) return true;
                }
            }
        }
        return false;
    }

    private static List<String> spellings(String name) {
        return List.of(name, name.toUpperCase(Locale.ROOT), name.toLowerCase(Locale.ROOT)).stream()
                .distinct().toList();
    }
}
